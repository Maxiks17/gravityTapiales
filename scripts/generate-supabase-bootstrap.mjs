const outputPath = path.join(repoRoot, 'database', 'bootstrap', 'mrbdedmaaljdwkxdniqt_bootstrap.sql');
const outputDir = path.dirname(outputPath);
const chunkDir = path.join(outputDir, 'mrbdedmaaljdwkxdniqt_chunks');
const manifestPath = path.join(outputDir, 'mrbdedmaaljdwkxdniqt_manifest.json');

function normalizeNewlines(text) {
  return text.replace(/\r\n/g, '\n');
}

async function readIfExists(relPath) {
  const absPath = path.join(repoRoot, relPath);
  try {
    const content = await fs.readFile(absPath, 'utf8');
    return { relPath, content: normalizeNewlines(content) };
  } catch (err) {
    if (err && (err.code === 'ENOENT' || err.code === 'ENOTDIR')) {
      return { relPath, missing: true };
    }
    throw err;
  }
}

function extractSqlCodeBlocks(markdown) {
  const blocks = [];
  const re = /```sql\s*\n([\s\S]*?)\n```/g;
  let match;
  while ((match = re.exec(markdown)) !== null) {
    blocks.push(match[1].trimEnd());
  }
  return blocks;
}

function toChunkFileName(index, relPath) {
  const base = relPath
    ? path
        .basename(relPath)
        .replace(/[^a-zA-Z0-9._-]+/g, '-')
        .replace(/-+/g, '-')
        .replace(/^-|-$/g, '')
    : 'chunk';
  const baseNoSql = base.toLowerCase().endsWith('.sql') ? base.slice(0, -4) : base;
  return `${String(index).padStart(4, '0')}_${baseNoSql || 'chunk'}.sql`;
}

async function main() {
  const parts = [];
  const chunks = [];
  let chunkIndex = 0;

  const header = normalizeNewlines(
    `-- =====================================================\n-- BOOTSTRAP SQL (single-file)\n-- Project ref (source): mrbdedmaaljdwkxdniqt\n-- Generated by: scripts/generate-supabase-bootstrap.mjs\n-- Date (local): ${new Date().toISOString()}\n--\n-- Notes:\n-- - Intended for a NEW/EMPTY Supabase database.\n-- - Includes schema, functions, triggers, RLS policies, FKs, and reference seed data found in repo SQL.\n-- - Supabase Auth settings (e.g. enabling hooks in Dashboard) are not fully expressible in SQL;\n--   this script only creates the hook function & grants.\n-- =====================================================\n\n`
  );

  const prelude = `${header}begin;\n\n-- Required for gen_random_uuid()\ncreate extension if not exists \"pgcrypto\";\n\ncommit;\n`;
  chunks.push({
    index: chunkIndex,
    file: toChunkFileName(chunkIndex, 'prelude'),
    source: 'prelude',
    content: prelude,
  });
  chunkIndex++;

  parts.push(`${header}begin;\n\n-- Required for gen_random_uuid()\ncreate extension if not exists \"pgcrypto\";\n\n`);

  for (const relPath of filesInOrder) {
    const file = await readIfExists(relPath);
    if (file.missing) {
      parts.push(`-- =====================================================\n-- MISSING FILE (skipped): ${relPath}\n-- =====================================================\n\n`);
      chunks.push({
        index: chunkIndex,
        file: toChunkFileName(chunkIndex, relPath),
        source: relPath,
        missing: true,
        content: normalizeNewlines(
          `-- =====================================================\n-- MISSING FILE (skipped): ${relPath}\n-- =====================================================\n\n`
        ),
      });
      chunkIndex++;
      continue;
    }

    parts.push(`-- =====================================================\n-- FILE: ${relPath}\n-- =====================================================\n\n`);
    parts.push(file.content.trimEnd());
    parts.push('\n\n');

    chunks.push({
      index: chunkIndex,
      file: toChunkFileName(chunkIndex, relPath),
      source: relPath,
      content: normalizeNewlines(
        `-- =====================================================\n-- FILE: ${relPath}\n-- =====================================================\n\nbegin;\n\n${file.content.trimEnd()}\n\ncommit;\n`
      ),
    });
    chunkIndex++;
  }

  // Add SQL blocks from docs (JWT hook, grants, policies)
  const hookDocRel = 'docs/supabase/add_custom_claims_to_jwt.md';
  const hookDoc = await readIfExists(hookDocRel);
  if (!hookDoc.missing) {
    const blocks = extractSqlCodeBlocks(hookDoc.content);
    parts.push(`-- =====================================================\n-- DOC-EXTRACT: ${hookDocRel}\n-- =====================================================\n\n`);
    if (blocks.length === 0) {
      parts.push(`-- No SQL code blocks found in ${hookDocRel}\n\n`);
    } else {
      const chunkParts = [];
      for (let i = 0; i < blocks.length; i++) {
        parts.push(`-- ---- SQL BLOCK ${i + 1} ----\n`);
        parts.push(blocks[i]);
        parts.push('\n\n');

        chunkParts.push(`-- ---- SQL BLOCK ${i + 1} ----\n`);
        chunkParts.push(blocks[i]);
        chunkParts.push('\n\n');
      }

      chunks.push({
        index: chunkIndex,
        file: toChunkFileName(chunkIndex, hookDocRel),
        source: hookDocRel,
        content: normalizeNewlines(
          `-- =====================================================\n-- DOC-EXTRACT: ${hookDocRel}\n-- =====================================================\n\nbegin;\n\n${chunkParts.join('').trimEnd()}\n\ncommit;\n`
        ),
      });
      chunkIndex++;
    }
  }

  parts.push('commit;\n');

  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, parts.join(''), 'utf8');

  await fs.mkdir(chunkDir, { recursive: true });
  for (const chunk of chunks) {
    await fs.writeFile(path.join(chunkDir, chunk.file), chunk.content, 'utf8');
  }

  await fs.writeFile(
    manifestPath,
    JSON.stringify(
      {
        project_ref_source: 'mrbdedmaaljdwkxdniqt',
        generated_at: new Date().toISOString(),
        single_file: path.relative(repoRoot, outputPath).replace(/\\/g, '/'),
        chunk_dir: path.relative(repoRoot, chunkDir).replace(/\\/g, '/'),
        chunks: chunks.map(({ index, file, source, missing }) => ({
          index,
          file,
          source,
          ...(missing ? { missing: true } : {}),
        })),
      },
      null,
      2
    ),
    'utf8'
  );

  console.log(`Wrote bootstrap SQL to: ${outputPath}`);
  console.log(`Wrote chunked SQL to: ${chunkDir}`);
  console.log(`Wrote manifest to: ${manifestPath}`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
